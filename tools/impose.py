CRUSH_FIX = True          # main() sets from --no-crush-fix
CRUSH_LOG = []            # human lines describing what was lifted

IN = 72.0
SHEETS = {
    "letter": (8.5, 11), "legal": (8.5, 14), "tabloid": (11, 17), "ledger": (17, 11),
    "12x18": (12, 18), "13x19": (13, 19), "a4": (8.27, 11.69), "a3": (11.69, 16.54),
}
TOL = 2.0  # points — how far a page box may differ from trim and still count as "at trim"


def parse_size(s):
    """'5x7' or 'letter' or '5x7L' (force landscape) -> (w_in, h_in)."""
    s = s.strip().lower()
    force = None
    if s.endswith("l") and "x" in s:
        force, s = "L", s[:-1]
    if s.endswith("p") and "x" in s:
        force, s = "P", s[:-1]
    if s in SHEETS:
        w, h = SHEETS[s]
    else:
        try:
            w, h = (float(v) for v in s.split("x"))
        except Exception:
            sys.exit(f"Bad size '{s}'. Use WxH in inches (e.g. 5x7) or one of {', '.join(SHEETS)}.")
    if force == "L" and w < h or force == "P" and w > h:
        w, h = h, w
    return w, h


def fmt_size(w_in, h_in):
    def f(v):
        return f"{v:g}"
    return f"{f(w_in)}x{f(h_in)}"


def sheet_name(w_in, h_in):
    for name, (sw, sh) in SHEETS.items():
        if (abs(sw - w_in) < 0.01 and abs(sh - h_in) < 0.01) or (abs(sh - w_in) < 0.01 and abs(sw - h_in) < 0.01):
            return name
    return fmt_size(w_in, h_in)


# --------------------------------------------------------------------------- sources
@dataclass
class Piece:
    """One piece of art ready to place: a form XObject plus optional bleed strips."""
    label: str
    kind: str            # 'pdf' or 'image'
    src_w: float         # art box size in points (as drawn, before any rotation)
    src_h: float
    rotate: int          # 0 or 90 — applied so long side matches trim long side
    has_bleed: bool      # source already contains the bleed
    dpi: float | None    # effective dpi for images
    xobj: object = None  # pikepdf form xobject (copied into out pdf later)
    strips: list = None  # [(pil_image, x_in_bleedbox, y, w, h)] mirrored bleed strips
    pdf_page: object = None
    bleed_fill: dict = None  # generated bleed per side: {'left': 'reflect'|'edge', ...}
    bleed_why: dict = None   # sides switched to edge: {side: (run_in, col_px)}
    cmyk_bleed: bool = False # generated bleed rendered straight to CMYK (Ghostscript)


def load_source(path, pdf_out, trim_pt, bleed_pt, bleed_mode, dpi, raster_dpi):
    """Return list[Piece] from a PDF or image path."""
    ext = os.path.splitext(path)[1].lower()
    if ext == ".pdf":
        return load_pdf(path, pdf_out, trim_pt, bleed_pt, bleed_mode, raster_dpi)
    return [load_image(path, pdf_out, trim_pt, bleed_pt, bleed_mode, dpi)]


def classify(art_w, art_h, trim_pt, bleed_pt):
    """Decide rotation and whether the art box already includes bleed.
    Returns (rotate, has_bleed) or raises ValueError with the measured size."""
    tw, th = trim_pt
    bw, bh = tw + 2 * bleed_pt, th + 2 * bleed_pt
    for rot, (w, h) in ((0, (art_w, art_h)), (90, (art_h, art_w))):
        if abs(w - tw) <= TOL and abs(h - th) <= TOL:
            return rot, False
        if abs(w - bw) <= TOL and abs(h - bh) <= TOL:
            return rot, True
    raise ValueError(
        f"art box is {art_w/IN:.3f}x{art_h/IN:.3f} in; expected trim {tw/IN:g}x{th/IN:g} "
        f"or trim+bleed {bw/IN:g}x{bh/IN:g}. Not scaling — pass --trim to match, or fix the source.")


def crush_guard_pdf(src, label):
    """Lift crush colors in an opened source PDF (in memory only; the customer file is never written)."""
    if not CRUSH_FIX:
        return
    rep = crushcheck.check_pdf(src, fix=True, images="auto")
    lines, _, _ = crushcheck.summarise(rep, verbose=False)
    for l in lines:
        if l.startswith("LIFT"):
            CRUSH_LOG.append(f"{label}: {l[6:]}")


def crush_guard_image(img, label):
    if not CRUSH_FIX:
        return img
    new, share, flats = crushcheck.fix_pil(img)
    if flats:
        CRUSH_LOG.append(f"{label}: flat crush color " + ", ".join(f"{h} L*{L:.0f} ({s:.0%} of pixels)" for h, L, s in flats)
                         + " — chromatic shadows lifted, neutrals untouched")
    return new


def load_pdf(path, pdf_out, trim_pt, bleed_pt, bleed_mode, raster_dpi):
    src = pikepdf.open(path)
    crush_guard_pdf(src, os.path.basename(path))
    pieces = []
    for i, page in enumerate(src.pages):
        full = page.cropbox if "/CropBox" in page.obj else page.mediabox
        fx0, fy0, fx1, fy1 = norm_box(full)
        rot_flag = int(page.obj.get("/Rotate", 0)) % 360
        x0, y0, x1, y1 = fx0, fy0, fx1, fy1
        if "/TrimBox" in page.obj or "/BleedBox" in page.obj:
            # Source declares a trim: use it, and take exactly `bleed` around it if the page has it.
            tx0, ty0, tx1, ty1 = norm_box(page.trimbox if "/TrimBox" in page.obj else page.bleedbox)
            if trim_pt is None:
                trim_pt = ((tx1 - tx0, ty1 - ty0) if rot_flag not in (90, 270) else (ty1 - ty0, tx1 - tx0))
            avail = min(tx0 - fx0, ty0 - fy0, fx1 - tx1, fy1 - ty1)
            if avail + 0.5 >= bleed_pt:
                x0, y0, x1, y1 = tx0 - bleed_pt, ty0 - bleed_pt, tx1 + bleed_pt, ty1 + bleed_pt
            else:
                x0, y0, x1, y1 = tx0, ty0, tx1, ty1
                if avail > 0.5:
                    print(f"note: {os.path.basename(path)} p{i+1} has only {avail/IN:.3f} in of bleed; "
                          f"need {bleed_pt/IN:g} — mirroring instead", file=sys.stderr)
        art_w, art_h = x1 - x0, y1 - y0
        if rot_flag in (90, 270):
            art_w, art_h = art_h, art_w
        if trim_pt is None:
            trim_pt = (art_w, art_h)  # --trim auto: first page defines trim
        if bleed_pt == 0:
            # No-bleed output but the page is trim + equal bleed all round: clip it to trim.
            for tw_, th_ in (trim_pt, trim_pt[::-1]):
                bx, by = (art_w - tw_) / 2, (art_h - th_) / 2
                if 0.5 < bx <= 0.25 * IN and abs(bx - by) <= TOL:
                    x0, y0, x1, y1 = x0 + bx, y0 + bx, x1 - bx, y1 - bx
                    art_w, art_h = art_w - 2 * bx, art_h - 2 * bx
                    print(f"note: {os.path.basename(path)} p{i+1} carries {bx/IN:.3f} in bleed — clipped to trim "
                          f"(no-bleed output)", file=sys.stderr)
                    break
        rotate, has_bleed = classify(art_w, art_h, trim_pt, bleed_pt)
        # Normalise boxes so the form xobject's BBox is exactly the art box.
        page.mediabox = pikepdf.Array([x0, y0, x1, y1])
        page.cropbox = pikepdf.Array([x0, y0, x1, y1])
        # qpdf builds the form's /BBox from the TrimBox, so an inset TrimBox (InDesign export
        # with bleed) would clip the art to trim and shift it by the bleed. Normalise all boxes.
        for key in ("/TrimBox", "/BleedBox", "/ArtBox"):
            if key in page.obj:
                page.obj[key] = pikepdf.Array([x0, y0, x1, y1])
        xobj = pdf_out.copy_foreign(page.as_form_xobject())
        offx, offy = xobject_origin(xobj)
        piece = Piece(label=f"{os.path.basename(path)} p{i+1}", kind="pdf", src_w=art_w, src_h=art_h,
                      rotate=rotate, has_bleed=has_bleed, dpi=None, xobj=xobj, strips=[])
        piece.origin = (offx, offy)
        if not has_bleed and bleed_mode != "white" and bleed_pt > 0:
            img = render_page(src, i, raster_dpi)
            ink = None
            if page_is_cmyk(src.pages[i]):
                ink = render_page_cmyk(src, i, raster_dpi, img.size)
                if ink is None:
                    print(f"WARNING: {os.path.basename(path)} p{i+1} is CMYK but Ghostscript isn't installed — "
                          f"bleed strips rendered RGB (naive CMYK->RGB); bleed color may not match the trim",
                          file=sys.stderr)
                else:
                    piece.cmyk_bleed = True
            piece.strips, piece.bleed_fill, piece.bleed_why = make_strips(img, bleed_pt, raster_dpi, rotate, bleed_mode, ink=ink)
        pieces.append(piece)
    pieces[0].trim_pt = trim_pt
    return pieces


def norm_box(box):
    x0, y0, x1, y1 = (float(v) for v in box)
    return min(x0, x1), min(y0, y1), max(x0, x1), max(y0, y1)


def xobject_origin(xobj):
    """Bottom-left of the form xobject's drawing after its own /Matrix (so we can shift it to 0,0)."""
    x0, y0, x1, y1 = (float(v) for v in xobj.BBox)
    m = pikepdf.Matrix(*[float(v) for v in xobj.get("/Matrix", [1, 0, 0, 1, 0, 0])])
    pts = [m.transform((x, y)) for x in (x0, x1) for y in (y0, y1)]
    return min(p[0] for p in pts), min(p[1] for p in pts)


def render_page(src, index, dpi):
    """Render one (already box-normalised) page of an open pikepdf to a PIL image via pdftoppm."""
    with tempfile.TemporaryDirectory() as td:
        tmp = os.path.join(td, "page.pdf")
        one = pikepdf.new()
        one.pages.append(src.pages[index])
        one.save(tmp)
        out = os.path.join(td, "p")
        # Force the raster to exactly box x dpi. pdftoppm rounds the size up, so a 5.5 in page
        # whose box isn't at the origin (Canva) can come back 1651 px wide with a blank last
        # column — mirrored into the bleed, that lands as a white hairline on the trim.
        x0, y0, x1, y1 = norm_box(src.pages[index].cropbox if "/CropBox" in src.pages[index].obj
                                  else src.pages[index].mediabox)
        pw, ph = max(1, round((x1 - x0) / IN * dpi)), max(1, round((y1 - y0) / IN * dpi))
        rot = int(src.pages[index].obj.get("/Rotate", 0)) % 180
        if rot == 90:
            pw, ph = ph, pw
        subprocess.run(["pdftoppm", "-r", str(dpi), "-scale-to-x", str(pw), "-scale-to-y", str(ph),
                        "-png", "-cropbox", tmp, out], check=True, capture_output=True)
        f = [x for x in os.listdir(td) if x.endswith(".png")][0]
        img = Image.open(os.path.join(td, f)).convert("RGB")
        if img.size != (pw, ph):  # belt and braces: never mirror a stray column/row
            img = img.crop((0, 0, min(img.width, pw), min(img.height, ph))).resize((pw, ph), Image.LANCZOS)
        return img



RGB_CS = {"/DeviceRGB", "/CalRGB", "/Lab"}
OK_CS = {"/DeviceCMYK", "/DeviceGray", "/CalGray"}


def _cs_ok(cs, resources):
    """True when a color space resolves to CMYK/gray only (Separation/DeviceN/Pattern -> False:
    leave those to the RGB path rather than guess)."""
    try:
        if isinstance(cs, pikepdf.Name):
            n = str(cs)
            if n in OK_CS:
                return True
            if n in RGB_CS or n == "/Pattern":
                return False
            named = resources.get("/ColorSpace", {}) if resources is not None else {}
            if n in named:
                return _cs_ok(named[n], resources)
            return False
        if isinstance(cs, pikepdf.Array) and len(cs):
            fam = str(cs[0])
            if fam == "/ICCBased":
                return int(cs[1].get("/N", 3)) in (1, 4)
            if fam == "/Indexed":
                return _cs_ok(cs[1], resources)
            if fam in OK_CS:
                return True
    except Exception:
        pass
    return False


def page_is_cmyk(page):
    """True when every color on the page (content, nested forms, images, shadings, transparency
    group) is DeviceCMYK / DeviceGray (or ICC N=4/1). Such a page's bleed is rendered straight to
    CMYK so the strips carry the file's own numbers instead of pdftoppm's naive CMYK->RGB guess,
    which renders dark CMYK far darker than it prints (IGC Mock Meet, 2026-10-29: 71/44/73/73
    drawn as L*16 instead of L*25)."""
    seen = set()
    has_cmyk = [False]

    def group_ok(obj):
        g = obj.get("/Group")
        return g is None or "/CS" not in g or _cs_ok(g.CS, None)

    def walk(stream_owner, resources, depth=0):
        if depth > 12:
            return False
        try:
            ops = pikepdf.parse_content_stream(stream_owner)
        except Exception:
            return False
        res = resources if resources is not None else pikepdf.Dictionary()
        for ins in ops:
            operands, o = ins.operands, str(ins.operator)
            if o in ("rg", "RG"):
                return False
            if o in ("k", "K"):
                has_cmyk[0] = True
            if o in ("cs", "CS") and operands and not _cs_ok(operands[0], res):
                return False
            if o == "sh":
                sh = res.get("/Shading", {}).get(str(operands[0])) if operands else None
                if sh is None or not _cs_ok(sh.get("/ColorSpace"), res):
                    return False
            if o == "Do" and operands:
                x = res.get("/XObject", {}).get(str(operands[0]))
                if x is None:
                    continue
                key = x.objgen
                if key in seen and key != (0, 0):
                    continue
                seen.add(key)
                st = str(x.get("/Subtype"))
                if st == "/Image":
                    if x.get("/ImageMask", False):
                        continue
                    cs = x.get("/ColorSpace")
                    if cs is None or not _cs_ok(cs, res):
                        return False
                    if str(cs) == "/DeviceCMYK" or (isinstance(cs, pikepdf.Array) and _cs_ok(cs, res)):
                        has_cmyk[0] = has_cmyk[0] or str(cs) != "/DeviceGray"
                elif st == "/Form":
                    if not group_ok(x) or not walk(x, x.get("/Resources", res), depth + 1):
                        return False
        return True

    try:
        if not group_ok(page.obj):
            return False
        # soft masks in ExtGStates carry their own groups — only gray/CMYK ones are safe
        for gs_ in page.Resources.get("/ExtGState", {}).values():
            sm = gs_.get("/SMask")
            if isinstance(sm, pikepdf.Dictionary) and "/G" in sm and not group_ok(sm.G):
                return False
        return walk(page, page.obj.get("/Resources")) and has_cmyk[0]
    except Exception:
        return False


def ghostscript():
    for c in ("gs", "gswin64c", "gswin32c"):
        p = shutil.which(c)
        if p:
            return p
    return None


def render_page_cmyk(src, index, dpi, size):
    """Render one page straight to an 8-bit CMYK PIL image with Ghostscript (tiff32nc), sized
    exactly `size` (the RGB render's size) so modes picked on the RGB raster apply pixel for pixel.
    DeviceCMYK content passes through with its own numbers. None when gs isn't installed."""
    gs = ghostscript()
    if gs is None:
        return None
    pw, ph = size
    with tempfile.TemporaryDirectory() as td:
        tmp = os.path.join(td, "page.pdf")
        one = pikepdf.new()
        one.pages.append(src.pages[index])
        one.save(tmp)
        out = os.path.join(td, "p.tif")
        subprocess.run([gs, "-q", "-dNOPAUSE", "-dBATCH", "-dSAFER", "-sDEVICE=tiff32nc",
                        f"-r{dpi}", "-dUseCropBox", "-dOverrideICC=false", f"-sOutputFile={out}", tmp],
                       check=True, capture_output=True)
        img = Image.open(out)
        img.load()
        if img.mode != "CMYK":
            return None
        if img.size != (pw, ph):
            img = img.crop((0, 0, min(img.width, pw), min(img.height, ph)))
            if img.size != (pw, ph):
                img = img.resize((pw, ph), Image.LANCZOS)
        return img

OVERLAP_PX = 2  # bleed strips tuck this far under the art (px at --raster-dpi)


EDGE_INSET_PX = 2  # edge mode: smear from this many px inside the trim (skips an antialiased edge row)


def side_modes(a, pad, mode, dpi):
    """Per-side fill. auto = mirror, except a side whose mirror band holds a hard edge parallel
    to the trim (box, QR, rule, big type within the bleed width) — that side is edge-extended so
    the element isn't copied into the bleed. reflect / edge force every side."""
    if mode in ("reflect", "edge"):
        return {k: mode for k in ("left", "right", "top", "bottom")}, {}
    return bleedscan.choose_modes(a, pad, dpi)


def pad_bleed(a, pad, modes):
    """Extend an HxWx3 array by `pad` px per side, each side by its mode. reflect = mirror the
    edge band; edge = repeat the pixel EDGE_INSET_PX in from the trim outward. Left/right first,
    then top/bottom over the result, so corners follow the top/bottom treatment consistently.
    The art inside the trim is never altered."""
    k = max(0, min(EDGE_INSET_PX, a.shape[0] // 4, a.shape[1] // 4))
    H, W = a.shape[:2]
    def ext(arr, n, mode, side):          # side: 'lo' or 'hi' along axis 1
        if mode == "edge":
            c = arr[:, k:k + 1] if side == "lo" else arr[:, arr.shape[1] - 1 - k:arr.shape[1] - k]
            return np.repeat(c, n, axis=1)
        if side == "lo":
            return arr[:, 1:n + 1][:, ::-1]
        return arr[:, arr.shape[1] - 1 - n:arr.shape[1] - 1][:, ::-1]
    p = np.concatenate([ext(a, pad, modes["left"], "lo"), a, ext(a, pad, modes["right"], "hi")], axis=1)
    t = np.swapaxes(p, 0, 1)
    t = np.concatenate([ext(t, pad, modes["top"], "lo"), t, ext(t, pad, modes["bottom"], "hi")], axis=1)
    p = np.ascontiguousarray(np.swapaxes(t, 0, 1))
    p[pad:pad + H, pad:pad + W] = a
    return p


def make_strips(img, bleed_pt, dpi, rotate, mode="auto", ink=None):
    """Mirror- (or edge-) extend the raster edges by `bleed` and return the 4 outer strips.
    Coordinates are in bleed-box space (origin bottom-left of bleed box, points),
    for the art *as rotated* into the trim orientation."""
    if rotate == 90:
        img = img.transpose(Image.Transpose.ROTATE_90)  # CCW, same as PDF +90
        if ink is not None:
            ink = ink.transpose(Image.Transpose.ROTATE_90)
    a = np.asarray(img)
    pad = int(round(bleed_pt / IN * dpi))
    pad = max(1, min(pad, a.shape[0] - 1, a.shape[1] - 1))
    modes, why = side_modes(a, pad, mode, dpi)   # chosen on the RGB raster
    # ink: the CMYK render of the same page (same size) — pad that instead, so the strips carry
    # the file's CMYK numbers; Image.fromarray of an HxWx4 array comes back as a CMYK image.
    p = pad_bleed(np.asarray(ink) if ink is not None else a, pad, modes)
    H, W = p.shape[:2]
    s = IN / dpi  # points per pixel
    # Each strip runs `ov` px inside the trim (a raster of the same art) and is drawn over the
    # vector art, so the trim/bleed join never shows an antialiased hairline.
    ov = max(0, min(OVERLAP_PX, (H - 2 * pad) // 2 - 1, (W - 2 * pad) // 2 - 1))
    strips = []
    if p.shape[2] == 4:
        Image_fromarray = lambda arr: Image.fromarray(np.ascontiguousarray(arr), mode="CMYK")
    else:
        Image_fromarray = Image.fromarray
    # top (full width), bottom (full width), left, right (between, overlapping top/bottom)
    strips.append((Image_fromarray(p[:pad + ov, :]), 0, (H - pad - ov) * s, W * s, (pad + ov) * s))
    strips.append((Image_fromarray(p[H - pad - ov:, :]), 0, 0, W * s, (pad + ov) * s))
    strips.append((Image_fromarray(p[pad - ov:H - pad + ov, :pad + ov]), 0, (pad - ov) * s, (pad + ov) * s, (H - 2 * pad + 2 * ov) * s))
    strips.append((Image_fromarray(p[pad - ov:H - pad + ov, W - pad - ov:]), (W - pad - ov) * s, (pad - ov) * s, (pad + ov) * s, (H - 2 * pad + 2 * ov) * s))
    return strips, modes, why


def load_image(path, pdf_out, trim_pt, bleed_pt, bleed_mode, dpi):
    img = ImageOps.exif_transpose(Image.open(path))
    if img.mode not in ("RGB", "L"):
        img = img.convert("RGB")
    if img.mode == "RGB":
        img = crush_guard_image(img, os.path.basename(path))
    px_w, px_h = img.size
    if trim_pt is None:
        # No trim given: use the image's own dpi (or --dpi) to define trim.
        idpi = dpi or (img.info.get("dpi") or (300, 300))[0]
        trim_pt = (px_w / idpi * IN, px_h / idpi * IN)
    tw, th = trim_pt
    # orientation: long side to long side
    rotate = 0
    if (px_w >= px_h) != (tw >= th) and tw != th and px_w != px_h:
        rotate = 90
    ew, eh = (px_h, px_w) if rotate else (px_w, px_h)
    aspect_img, aspect_trim = ew / eh, tw / th
    aspect_bleed = (tw + 2 * bleed_pt) / (th + 2 * bleed_pt)
    if bleed_pt == 0 and abs(aspect_img / aspect_trim - 1) > 0.002:
        # No-bleed output: an image built at trim + bleed gets its bleed cropped off.
        for b in (0.125 * IN, 0.1 * IN, 0.0625 * IN):
            if abs(aspect_img / ((tw + 2 * b) / (th + 2 * b)) - 1) <= 0.002:
                cx = int(round(b / (tw + 2 * b) * ew)); cy = int(round(b / (th + 2 * b) * eh))
                img = img.crop((cy, cx, px_w - cy, px_h - cx) if rotate else (cx, cy, px_w - cx, px_h - cy))
                px_w, px_h = img.size
                ew, eh = (px_h, px_w) if rotate else (px_w, px_h)
                aspect_img = ew / eh
                print(f"note: {os.path.basename(path)} carries {b/IN:g} in bleed — cropped to trim (no-bleed output)",
                      file=sys.stderr)
                break
    if abs(aspect_img / aspect_trim - 1) <= 0.01:
        has_bleed, box_w, box_h = False, tw, th
    elif abs(aspect_img / aspect_bleed - 1) <= 0.01:
        has_bleed, box_w, box_h = True, tw + 2 * bleed_pt, th + 2 * bleed_pt
    else:
        sys.exit(f"{os.path.basename(path)}: image aspect {ew}x{eh} px does not match trim "
                 f"{tw/IN:g}x{th/IN:g} (ratio {aspect_trim:.4f} vs {aspect_img:.4f}). Not cropping — "
                 f"crop it first (photo_prep.py) or pass the right --trim.")
    eff_dpi = ew / (box_w / IN)
    if rotate:
        img = img.transpose(Image.Transpose.ROTATE_90)
    fill, why = None, None
    if not has_bleed and bleed_mode != "white" and bleed_pt > 0:
        pad = int(round(bleed_pt / IN * eff_dpi))
        a = np.asarray(img.convert("RGB"))
        fill, why = side_modes(a, pad, bleed_mode, eff_dpi)
        a = pad_bleed(a, pad, fill)
        img = Image.fromarray(a)
        has_bleed = True
        box_w, box_h = tw + 2 * bleed_pt, th + 2 * bleed_pt
    xobj = image_xobject(pdf_out, img)
    piece = Piece(label=os.path.basename(path), kind="image", src_w=box_w, src_h=box_h, rotate=0,
                  has_bleed=has_bleed, dpi=eff_dpi, xobj=xobj, strips=[], bleed_fill=fill, bleed_why=why)
    piece.trim_pt = trim_pt
    return piece


def image_xobject(pdf_out, img, quality=95):
    if img.mode == "CMYK":
        # lossless, plain (non-inverted) DeviceCMYK — no JPEG Adobe-inversion ambiguity
        return pdf_out.make_stream(zlib.compress(img.tobytes(), 9), Type=pikepdf.Name.XObject,
                                   Subtype=pikepdf.Name.Image, Width=img.width, Height=img.height,
                                   ColorSpace=pikepdf.Name.DeviceCMYK, BitsPerComponent=8,
                                   Filter=pikepdf.Name.FlateDecode)
    buf = io.BytesIO()
    img.convert("RGB").save(buf, format="JPEG", quality=quality, dpi=(300, 300))
    return pdf_out.make_stream(buf.getvalue(), Type=pikepdf.Name.XObject, Subtype=pikepdf.Name.Image,
                               Width=img.width, Height=img.height, ColorSpace=pikepdf.Name.DeviceRGB,
                               BitsPerComponent=8, Filter=pikepdf.Name.DCTDecode)


