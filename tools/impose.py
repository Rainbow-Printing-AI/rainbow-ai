def choose_grid(nup, cols, rows, sheet_pt, cell_w, cell_h, gutter, mark):
    """Return (cols, rows, rotated_cells) that fits N pieces on the sheet."""
    sw, sh = sheet_pt

    def fits(c, r, cw, ch):
        need_w = c * cw + (c - 1) * gutter + 2 * mark
        need_h = r * ch + (r - 1) * gutter + 2 * mark
        return need_w <= sw + 0.01 and need_h <= sh + 0.01

    def capacity(cw, ch):
        c = int((sw - 2 * mark + gutter) // (cw + gutter))
        r = int((sh - 2 * mark + gutter) // (ch + gutter))
        return max(c, 0), max(r, 0)

    if cols and rows:
        for rot, (cw, ch) in ((False, (cell_w, cell_h)), (True, (cell_h, cell_w))):
            if fits(cols, rows, cw, ch):
                return cols, rows, rot
        sys.exit(f"{cols}x{rows} of {cell_w/IN:.2f}x{cell_h/IN:.2f} in (bleed box) does not fit on "
                 f"{sw/IN:g}x{sh/IN:g} with {gutter/IN:g} in gutters.")
    best = None
    for rot, (cw, ch) in ((False, (cell_w, cell_h)), (True, (cell_h, cell_w))):
        cmax, rmax = capacity(cw, ch)
        cap = cmax * rmax
        for c in range(1, cmax + 1):
            for r in range(1, rmax + 1):
                if c * r == nup:
                    # prefer the option whose grid is most square-ish to the sheet
                    score = abs((c * cw) / max(r * ch, 1) - sw / sh)
                    if best is None or score < best[0]:
                        best = (score, c, r, rot)
        if best is None:
            best_cap = (cap, rot, cmax, rmax) if best is None else best
    if best is None:
        caps = []
        for rot, (cw, ch) in ((False, (cell_w, cell_h)), (True, (cell_h, cell_w))):
            c, r = capacity(cw, ch)
            caps.append(f"{c}x{r}={c*r}{' (rotated)' if rot else ''}")
        sys.exit(f"{nup}-up does not fit on {sw/IN:g}x{sh/IN:g}. Max capacity: {', '.join(caps)}. "
                 f"Use --cols/--rows for an uneven grid or a bigger sheet.")
    return best[1], best[2], best[3]


def mark_segments(tx0, ty0, tw, th, bleed, mark):
    """8 crop-mark segments for a trim rect (x0,y0,w,h) — start at bleed edge, extend `mark` outward."""
    tx1, ty1 = tx0 + tw, ty0 + th
    segs = []
    for x in (tx0, tx1):            # vertical marks, top and bottom
        segs.append(((x, ty1 + bleed), (x, ty1 + bleed + mark)))
        segs.append(((x, ty0 - bleed), (x, ty0 - bleed - mark)))
    for y in (ty0, ty1):            # horizontal marks, left and right
        segs.append(((tx0 - bleed, y), (tx0 - bleed - mark, y)))
        segs.append(((tx1 + bleed, y), (tx1 + bleed + mark, y)))
    return segs


def build_sheet(pdf, pieces_for_sheet, slots, geom, args_mark_w, bleed):
    """Create one output page. pieces_for_sheet: list of Piece or None per slot."""
    sw, sh = geom["sheet_pt"]
    page = pdf.add_blank_page(page_size=(sw, sh))
    res_x = pikepdf.Dictionary()
    ops = []
    layout_pieces = []
    for k, (piece, (bx, by)) in enumerate(zip(pieces_for_sheet, slots)):
        # bx,by = bottom-left of the *bleed box* of this slot; slot may be rotated cells
        cw, ch = geom["cell_pt"]  # bleed box size as placed (already rotated if geom['rot_cells'])
        tx0, ty0 = bx + bleed, by + bleed
        tw, th = cw - 2 * bleed, ch - 2 * bleed
        layout_pieces.append({"trim": [round(tx0, 3), round(ty0, 3), round(tw, 3), round(th, 3)],
                              "label": piece.label if piece else None})
        if piece is not None and piece.bleed_fill:
            layout_pieces[-1]["bleed_fill"] = piece.bleed_fill
        if piece is None:
            continue
        rot_total = (piece.rotate + (90 if geom["rot_cells"] else 0)) % 180
        name = f"/Fm{k}"
        res_x[name] = piece.xobj
        # art box as drawn in its own coordinates (unrotated) has size src_w x src_h.
        # Determine where it lands: if it has bleed it fills the bleed box, else the trim.
        if piece.kind == "image":
            # image xobject draws in unit square; scale to its box
            dw, dh = piece.src_w, piece.src_h
            target_w, target_h = (cw, ch) if piece.has_bleed else (tw, th)
            ox, oy = (bx, by) if piece.has_bleed else (tx0, ty0)
            m = pikepdf.Matrix(dw, 0, 0, dh, 0, 0)
            m = m @ fit_matrix(dw, dh, target_w, target_h, ox, oy, 90 if geom["rot_cells"] else 0)
            ops.append(f"q {mat(m)} cm {name} Do Q")
        else:
            bb = [float(v) for v in piece.xobj.BBox]
            dw, dh = piece.src_w, piece.src_h   # size after /Rotate; xobject Matrix handles /Rotate
            target_w, target_h = (cw, ch) if piece.has_bleed else (tw, th)
            ox, oy = (bx, by) if piece.has_bleed else (tx0, ty0)
            # The form xobject's own /Matrix (from as_form_xobject) maps page space -> rotated space
            # with origin at 0,0 for the cropbox. We translate bbox origin to 0 then fit.
            offx, offy = piece.origin
            m = pikepdf.Matrix(1, 0, 0, 1, -offx, -offy) @ fit_matrix(dw, dh, target_w, target_h, ox, oy, rot_total)
            ops.append(f"q {mat(m)} cm {name} Do Q")
        # bleed strips (raster) drawn OVER the art's edge: each strip tucks OVERLAP_PX inside the
        # trim with a raster of the same art, so the join sits on matching pixels. Drawn under the
        # art instead, the art's antialiased clip edge conflates into a light hairline at the trim.
        # A PDF piece turned 90 to the trim AND sitting in a cell turned 90 for the sheet is drawn
        # at 0 (rot_total is mod 180), but its strips were built for the 90-turned art and get the
        # cell's 90 on top: 180 off, so each side's bleed lands on the opposite side
        # (IGC Mock Meet 5x7 2-up letter, 2026-10-29). Turn those strips 180 in their bleed box.
        flip180 = piece.kind == "pdf" and piece.rotate == 90 and geom["rot_cells"]
        ubw, ubh = (ch, cw) if geom["rot_cells"] else (cw, ch)   # strip frame (unrotated bleed box)
        for j, (im, sx, sy, swid, shei) in enumerate(piece.strips or []):
            if flip180:
                im = im.transpose(Image.Transpose.ROTATE_180)
                sx, sy = ubw - sx - swid, ubh - sy - shei
            sname = f"/Im{k}_{j}"
            res_x[sname] = image_xobject(pdf, im)
            ops.append(place_ops(sname, sx, sy, swid, shei, bx, by, cw, ch, 90 if geom["rot_cells"] else 0))
        # crop marks — only when asked (--marks), never inside the bleed
        if geom["mark_pt"] > 0:
            segs = mark_segments(tx0, ty0, tw, th, bleed, geom["mark_pt"])
            ops.append(f"q 0 0 0 1 K {args_mark_w} w 0 J")
            for (x0, y0), (x1, y1) in segs:
                ops.append(f"{x0:.3f} {y0:.3f} m {x1:.3f} {y1:.3f} l S")
            ops.append("Q")
    page.Resources = pikepdf.Dictionary(XObject=res_x)
    page.Contents = pdf.make_stream("\n".join(ops).encode())
    return layout_pieces


def fit_matrix(dw, dh, target_w, target_h, ox, oy, rot):
    """Matrix placing a (dw x dh) drawing, origin 0,0, into target rect at (ox,oy) rotated 0/90.
    No scaling other than what rotation implies; sizes are asserted to match."""
    if rot % 180 == 90:
        # rotate +90 (CCW): drawing width becomes height
        assert abs(dw - target_h) <= TOL + 0.5 and abs(dh - target_w) <= TOL + 0.5, (dw, dh, target_w, target_h)
        return pikepdf.Matrix(0, 1, -1, 0, ox + dh, oy)
    assert abs(dw - target_w) <= TOL + 0.5 and abs(dh - target_h) <= TOL + 0.5, (dw, dh, target_w, target_h)
    return pikepdf.Matrix(1, 0, 0, 1, ox, oy)


def place_ops(name, sx, sy, swid, shei, bx, by, cw, ch, rot):
    """Place an image strip given in unrotated bleed-box coords into the slot (possibly rotated 90)."""
    if rot == 90:
        # unrotated box (W x H) -> rotated slot (cw=H, ch=W): point (x,y) -> (bx + (H - y - h) ... )
        # rotate CCW about origin then translate: (x,y) -> (-y, x) shifted by +H in x
        m = pikepdf.Matrix(swid, 0, 0, shei, sx, sy) @ pikepdf.Matrix(0, 1, -1, 0, bx + cw, by)
    else:
        m = pikepdf.Matrix(swid, 0, 0, shei, bx + sx, by + sy)
    return f"q {mat(m)} cm {name} Do Q"


def mat(m):
    return " ".join(f"{v:.4f}" for v in (m.a, m.b, m.c, m.d, m.e, m.f))


# --------------------------------------------------------------------------- main
def bleed_desc(p, mode):
    d = _bleed_desc(p, mode)
    return d + (" (CMYK, file's own numbers)" if getattr(p, "cmyk_bleed", False) and mode != "white" else "")


def _bleed_desc(p, mode):
    if mode == "white":
        return "bleed white"
    f = p.bleed_fill or {}
    edge = [k for k in ("top", "bottom", "left", "right") if f.get(k) == "edge"]
    if not edge:
        return "bleed mirrored"
    if len(edge) == 4:
        return "bleed edge-extended"
    why = "; ".join(f"{k}: hard edge {p.bleed_why[k][0]:.2f} in long, {p.bleed_why[k][1]} px in from trim"
                    for k in edge if p.bleed_why and k in p.bleed_why)
    return f"bleed mirrored, edge-extended on {'/'.join(edge)}" + (f" ({why})" if why else "")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("source", help="PDF (any page count) or image (jpg/png/tif)")
    ap.add_argument("--back", help="PDF/image for the backs (duplex). Alternative: --duplex with F/B page pairs")
    ap.add_argument("--trim", help="trim size in inches WxH (default: the source page box)")
    ap.add_argument("--bleed", type=float, default=0.0, help="bleed per side, inches (default 0 — standing rule: no bleed unless the job asks)")
    ap.add_argument("--marks", action="store_true", help="add crop marks (off by default — standing rule: no crop marks unless the job asks)")
    ap.add_argument("--mark", type=float, default=0.125, help="crop mark length with --marks, inches (default 0.125)")
    ap.add_argument("--mark-width", type=float, default=0.25, help="crop mark stroke, points (default 0.25)")
    ap.add_argument("--bleed-mode", choices=["auto", "reflect", "edge", "white"], default="auto",
                    help="how to fill bleed when the source has none. auto (default): mirror each edge, "
                         "but edge-extend any side where a hard edge (box, QR, rule, big type) sits within the "
                         "bleed width of the trim and would be mirrored into the bleed. reflect / edge force "
                         "one method on every side; white leaves it blank")
    ap.add_argument("--nup", type=int, help="pieces per sheet (auto grid)")
    ap.add_argument("--cols", type=int); ap.add_argument("--rows", type=int)
    ap.add_argument("--sheet", help="output sheet: letter, tabloid, 12x18, 13x19, WxH. Default = trim (+bleed/+marks if asked), 1-up")
    ap.add_argument("--gutter", type=float, default=0.25, help="space between bleed boxes, inches (default 0.25)")
    ap.add_argument("--repeat", action="store_true", help="gang each source page N times (default for 1-page sources)")
    ap.add_argument("--sequence", action="store_true", help="fill sheets with consecutive pages (default for multipage)")
    ap.add_argument("--duplex", action="store_true", help="source pages alternate front/back")
    ap.add_argument("--flip", choices=["long", "short"], default="long", help="duplex flip edge (default long)")
    ap.add_argument("--dpi", type=float, help="assume this dpi for images without --trim")
    ap.add_argument("--raster-dpi", type=int, default=300, help="render dpi for mirrored bleed strips")
    ap.add_argument("--out", help="output path (default: auto-named next to the source)")
    ap.add_argument("--no-marks", action="store_true", help="no crop marks (the default; kept for old commands)")
    ap.add_argument("--no-crush-fix", action="store_true",
                    help="do not lift colors that crush to black on the Versant (see crushcheck.py / press.json)")
    args = ap.parse_args()
    global CRUSH_FIX
    CRUSH_FIX = not args.no_crush_fix

    bleed = args.bleed * IN
    mark = args.mark * IN if (args.marks and not args.no_marks) else 0.0
    trim_pt = tuple(v * IN for v in parse_size(args.trim)) if args.trim else None

    pdf = pikepdf.new()
    fronts = load_source(args.source, pdf, trim_pt, bleed, args.bleed_mode, args.dpi, args.raster_dpi)
    trim_pt = getattr(fronts[0], "trim_pt", trim_pt)
    backs = None
    if args.back:
        backs = load_source(args.back, pdf, trim_pt, bleed, args.bleed_mode, args.dpi, args.raster_dpi)
    elif args.duplex:
        if len(fronts) % 2:
            sys.exit("--duplex needs an even page count (front/back pairs).")
        fronts, backs = fronts[0::2], fronts[1::2]

    tw, th = trim_pt
    cell_w, cell_h = tw + 2 * bleed, th + 2 * bleed
    gutter = args.gutter * IN
    if mark > 0 and gutter < 2 * mark and (args.nup or args.cols):
        print(f"note: gutter {args.gutter:g} in < 2 x mark {2*args.mark:g} in — adjacent marks will join into one line", file=sys.stderr)

    if args.sheet:
        sheet_pt = tuple(v * IN for v in parse_size(args.sheet))
        n = args.nup or ((args.cols or 1) * (args.rows or 1))
        cols, rows, rot_cells = choose_grid(n, args.cols, args.rows, sheet_pt, cell_w, cell_h, gutter, mark)
    else:
        sheet_pt = (cell_w + 2 * mark, cell_h + 2 * mark)
        cols, rows, rot_cells = 1, 1, False
        if args.nup and args.nup > 1:
            sys.exit("--nup needs --sheet.")
    cw, ch = (cell_h, cell_w) if rot_cells else (cell_w, cell_h)
    n = cols * rows
    grid_w = cols * cw + (cols - 1) * gutter
    grid_h = rows * ch + (rows - 1) * gutter
    ox = (sheet_pt[0] - grid_w) / 2
    oy = (sheet_pt[1] - grid_h) / 2
    # slot order: top-left → right, then down (reading order)
    slots = []
    for r in range(rows):
        for c in range(cols):
            slots.append((ox + c * (cw + gutter), oy + grid_h - (r + 1) * ch - r * gutter))
    geom = {"sheet_pt": sheet_pt, "cell_pt": (cw, ch), "rot_cells": rot_cells, "mark_pt": mark}

    # assign pieces to sheets
    repeat = args.repeat or (len(fronts) == 1 and not args.sequence)
    def sheets_for(pieces):
        if repeat:
            return [[p] * n for p in pieces]
        out = []
        for i in range(0, len(pieces), n):
            chunk = pieces[i:i + n]
            out.append(chunk + [None] * (n - len(chunk)))
        return out

    def mirror(order):
        """Reorder back slots so they land behind their fronts after the flip."""
        sw, sh = sheet_pt
        portrait = sh >= sw
        mirror_cols = (args.flip == "long") == portrait
        grid = [order[r * cols:(r + 1) * cols] for r in range(rows)]
        if mirror_cols:
            grid = [row[::-1] for row in grid]
        else:
            grid = grid[::-1]
        return [x for row in grid for x in row]

    layout = {"tool": "impose.py", "trim_in": [tw / IN, th / IN], "bleed_in": args.bleed, "mark_in": mark / IN,
              "sheet_in": [sheet_pt[0] / IN, sheet_pt[1] / IN], "cols": cols, "rows": rows,
              "rotated_cells": rot_cells, "gutter_in": args.gutter, "duplex": backs is not None,
              "flip": args.flip if backs is not None else None, "sheets": [],
              "crush_fix": CRUSH_FIX, "crush_lifted": list(CRUSH_LOG)}

    front_sheets = sheets_for(fronts)
    back_sheets = sheets_for(backs) if backs else None
    if backs and len(back_sheets) != len(front_sheets):
        sys.exit(f"front/back page counts differ ({len(fronts)} vs {len(backs)}).")
    for si, fs in enumerate(front_sheets):
        lp = build_sheet(pdf, fs, slots, geom, args.mark_width, bleed)
        layout["sheets"].append({"side": "front", "pieces": lp})
        if backs:
            bs = mirror(back_sheets[si])
            lp = build_sheet(pdf, bs, slots, geom, args.mark_width, bleed)
            layout["sheets"].append({"side": "back", "pieces": lp})

    # output name: <stem>_<trim>_<Nup>_<sheet>_cropmarks[_duplex].pdf
    stem = os.path.splitext(os.path.basename(args.source))[0]
    if not args.out:
        parts = [stem, fmt_size(tw / IN, th / IN)]
        if n > 1:
            parts.append(f"{n}up")
        parts.append(sheet_name(*layout["sheet_in"]) if args.sheet else "1up")
        if mark > 0:
            parts.append("cropmarks")
        elif bleed > 0:
            parts.append("bleed")
        if backs:
            parts.append("duplex")
        args.out = os.path.join(os.path.dirname(os.path.abspath(args.source)), "_".join(parts) + ".pdf")
    with pdf.open_metadata() as meta:
        meta["dc:title"] = os.path.basename(args.out)
    pdf.docinfo["/RainbowLayout"] = json.dumps(layout)
    pdf.docinfo["/Producer"] = "Rainbow impose.py"
    pdf.save(args.out, linearize=True)

    # report
    print(f"wrote {args.out}")
    print(f"  trim {tw/IN:g}x{th/IN:g} in, bleed {args.bleed:g} in, marks {mark/IN:g} in")
    print(f"  sheet {layout['sheet_in'][0]:g}x{layout['sheet_in'][1]:g} in, {cols}x{rows} = {n}-up"
          f"{' (cells rotated 90)' if rot_cells else ''}, {len(pdf.pages)} page(s){', duplex ' + args.flip + '-edge flip' if backs else ''}")
    for p in fronts + (backs or []):
        extra = f", {p.dpi:.0f} dpi" if p.dpi else ""
        print(f"  {p.label}: {'no bleed' if bleed == 0 else (bleed_desc(p, args.bleed_mode) if (p.bleed_fill or not p.has_bleed) else 'has bleed')}"
              f"{', rotated 90' if p.rotate else ''}{extra}")
        if p.dpi and p.dpi < 200:
            print(f"    WARNING: {p.dpi:.0f} dpi at this size will look soft.")
    if CRUSH_LOG:
        print(f"  crush guard: {len(CRUSH_LOG)} color(s) too dark for the Versant to show a hue were lifted (hue kept):")
        for l in CRUSH_LOG:
            print(f"    {l}")
        print("  >>> TELL ANDREW: colors were changed in this file (list above). Always report every lift. <<<")
    elif CRUSH_FIX:
        print("  crush guard: no color will crush to black")
    else:
        print("  crush guard OFF (--no-crush-fix) — verify_print.py will flag any crush color")
    print("  next: python3 verify_print.py \"%s\"" % args.out)


if __name__ == "__main__":
    main()
