#!/usr/bin/env python3
"""
impose.py — Rainbow Printing imposition tool.

Takes customer art (PDF pages or images) and gangs it N-up onto a sheet.
Encodes Andrew's standing rules:

  * NO bleed and NO crop marks by default (standing rule since 2026-09-30).
    Only when a job asks for them: --bleed 0.1 adds bleed, --marks adds 0.125 in
    hairline crop marks that start exactly at the bleed edge, never in the bleed.
  * a source that carries bleed (TrimBox, or page = trim + 2x bleed) is clipped to trim
  * 1-up sheet = trim (+ 2*bleed + 2*mark only if asked) with no extra white space,
    unless --sheet
  * art is never scaled or cropped to fit; art is rotated so its long side matches
    the trim's long side
  * vector stays vector — pages are placed as form XObjects; only the bleed strips
    are rasterised when bleed has to be generated by mirroring
  * duplex: page 1 = fronts, page 2 = backs, identical grid, back columns/rows
    mirrored for the chosen flip edge
  * crush guard (crushcheck.py): chromatic colors too dark for the Versant to show
    a hue (L* < l_crush in press.json) are lifted to l_fix, same hue, before
    placement; neutrals, blacks and every printable color stay untouched.
    --no-crush-fix disables it (verify_print.py will then fail the file).

The finished PDF carries a JSON description of the layout in its document info
(/RainbowLayout) so verify_print.py can check it against the rendered ink.

Examples
  impose.py card.pdf                                  # 1-up at trim, no bleed/marks
  impose.py card.pdf --bleed 0.1 --marks              # only when the job calls for it
  impose.py card.pdf --nup 2 --sheet letter           # 2-up on 8.5x11
  impose.py front.png --back back.png --nup 8 --sheet letter --trim 3.5x2
  impose.py tags.pdf --trim 5x5 --nup 2 --sheet letter   # multipage → sequence
  impose.py flyer.pdf --trim 4x6 --nup 4 --sheet letter --repeat
  impose.py art_with_bleed.pdf --trim 5x7             # page = trim+2*bleed → clipped to trim

Sizes are inches: "5x7", "8.5x11", or a name (letter, tabloid, 12x18, 13x19).
"""
